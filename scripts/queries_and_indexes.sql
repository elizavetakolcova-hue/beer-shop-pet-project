-- Запрос 1 (WHERE): Товары с ценой выше заданного порога — фильтрация по цене. 
select Код_товара, Название, Цена
from Товар
where Цена > 300;
-- Запрос 2 (GROUP BY, ORDER BY): Суммарное количество проданного по каждому товару, отсортировано по убыванию — выявляет самые продаваемые товары.
select Код_товара, SUM(Количество) as суммарное_количество
from "Товары_в_продаже"
group by Код_товара
order by суммарное_количество desc;
-- Запрос 3 (GROUP BY, HAVING): Товары, суммарно проданные в количестве больше 10 штук — фильтрация по результату агрегации.
select Код_товара, Количество
from "Товары_в_продаже"
group by Код_товара
having SUM(Количество) > 10
order by Количество;
-- Запрос 4 (INNER JOIN): Продажи с указанием ФИО клиента и названия купленного товара — соединение четырёх таблиц.
select к.ФИО, п.Код_продажи, т.Название
from Клиент к
join Продажи п on к.Код_клиента = п.Код_клиента
join Товары_в_продаже твп on п.Код_продажи = твп.Код_продажи
join Товар т on твп.Код_товара = т.Код_товара;
-- Запрос 5 (LEFT JOIN): Все клиенты и их продажи, включая клиентов без единой покупки (если такие есть в данных).
select к.Код_клиента, к.ФИО, п.Код_продажи
from Клиент к
left join Продажи п on к.Код_клиента = п.Код_клиента;
-- Запрос 6 (RIGHT/FULL JOIN): Товары и их поставщики, включая случаи без совпадений с одной из сторон.
select т.Код_товара, т.Название, п.Код_поставщика, п.Название_пивоварни
from Товар т 
full join Поставщик п on т.Код_поставщика = п.Код_поставщика;
-- Запрос 7 (скалярный подзапрос/LIMIT): Топ 3 товара, чья цена выше средней цены по всем товарам.
select Код_товара, Название, Цена
from Товар 
where Цена > (select AVG(Цена) from Товар)
order by Цена
limit 3;
-- Запрос 8 (подзапрос с IN): Клиенты, которые хотя бы раз покупали товары от конкретного поставщика.
select Код_клиента, ФИО
from Клиент
where Код_клиента in (
 select п.Код_клиента 
 from Продажи п 
 join Товары_в_продаже твп on п.Код_продажи = твп.Код_продажи
 join Товар т on твп.Код_товара = т.Код_товара
 where т.Код_поставщика = 5);
-- Запрос 9 (подзапрос с EXISTS): Поставщики, у которых есть хотя бы один товар с остатком на складе больше 0.
select Код_поставщика, Название_пивоварни
from Поставщик
where exists (
select 1
from Товар
where Товар.Код_поставщика = Поставщик.Код_поставщика and Остаток_в_складе > 0
);
-- Запрос 10 (подзапрос с ANY/ALL): Товары дороже, чем любой (ANY) товар определённого поставщика.
select Код_товара, Название, Цена
from Товар
where Цена > any (
 select Цена
 from Товар т
 join Поставщик п on т.Код_поставщика = п.Код_поставщика
 where п.Город = 'Москва'
 )
order by Цена;
-- Запрос 11 (самосоединение / self-join): Клиенты одного уровня лояльности, сопоставленные попарно, без дублей и пар "сам с собой".
select к1.Код_клиента as Клиент_1, 
       к2.Код_клиента as Клиент_2,
       к1.Код_уровня
from Клиент к1
join Клиент к2 on к1.Код_уровня = к2.Код_уровня
                and к1.Код_клиента < к2.Код_клиента;
-- Запрос 12 (оконная функция RANK, PARTITION BY): Ранжирование товаров по суммарной выручке внутри каждого поставщика.
with выручка_по_товару as (
  select т.Код_товара, т.Название, т.Код_поставщика,
   SUM(твп.Количество * твп.Цена_за_единицу) as Суммарная_выручка
  from Товары_в_продаже твп 
  join Товар т on твп.Код_товара = т.Код_товара
  group by т.Код_товара, т.Название, т.Код_поставщика
)
select Код_товара, 
       Название,
       Код_поставщика, 
       Суммарная_выручка,
       RANK() over (partition by Код_поставщика order by Суммарная_выручка desc) as Ранг
from выручка_по_товару;
       
-- Запрос 13 (оконная функция SUM OVER, ORDER BY): Накопительная (кумулятивная) сумма выручки по датам продаж.
with выручка_по_дате as(
 select п.Дата,
        SUM(твп.Количество * твп.Цена_за_единицу) as дневная_выручка
 from Продажи п
 join Товары_в_продаже твп on п.Код_продажи = твп.Код_продажи
 join Товар т on твп.Код_товара = т.Код_товара
 group by п.Дата
)
select Дата,
       SUM(дневная_выручка) over(order by Дата) as Накопительная_сумма
from выручка_по_дате;
-- Запрос 14 (оконная функция LAG): Сравнение суммы текущей продажи клиента с суммой его предыдущей покупки.
with сумма_по_продаже as(
 select п.Код_продажи, 
        п.Код_клиента,
        п.Дата,
        SUM(твп.Количество * твп.Цена_за_единицу) AS сумма
        from Продажи п
        join Товары_в_продаже твп on п.Код_продажи = твп.Код_продажи
        join Товар т on твп.Код_товара = т.Код_товара
        group by п.Код_продажи,п.Код_клиента, п.Дата
        )
select Код_клиента, 
       Дата, 
       сумма,
       lag (сумма) over (partition by Код_клиента order by Дата)
from сумма_по_продаже;
-- Запрос 15 (математическая оконная функция ROUND + SUM OVER ()): Процент, который выручка каждого товара составляет от общей выручки магазина.
with выручка_по_товару as(
  select т.Код_товара,
         т.Название, 
         SUM(твп.Количество * твп.Цена_за_единицу) AS выручка
  from Товары_в_продаже твп
  join Товар т on твп.Код_товара = т.Код_товара
  group by т.Код_товара, т.Название)
  
 select Код_товара, 
        Название,
        выручка,
        ROUND(выручка / SUM(выручка) over () * 100, 2) as процент_от_общей_выручки
 from выручка_по_товару;
 -- Запрос 16 (рекурсивный запрос, WITH RECURSIVE): Цепочка уровней лояльности клиента
with recursive цепочка_уровней as (
    select
        Код_клиента,
        Код_уровня as текущий_код_уровня,
        Код_предыдущего_уровня,
        1 as глубина
    from Клиент

    UNION ALL

   select
        ц.Код_клиента,
        к.Код_предыдущего_уровня as текущий_код_уровня,
        к.Код_предыдущего_уровня,
        ц.глубина + 1
    from цепочка_уровней ц
    join Клиент к on ц.Код_клиента = к.Код_клиента
    where ц.Код_предыдущего_уровня is not null
      and ц.глубина < 2
)
select * from цепочка_уровней
order by Код_клиента, глубина;
 
